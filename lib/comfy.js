/** @returns {Promise<{port:number, stats:object}|null>} */
export async function probePort(port) {
  try {
    const stats = await getJson(`http://127.0.0.1:${port}/system_stats`, 2500)
    return { port, stats }
  } catch {
    return null
  }
}

export async function findAttached(cfg) {
  for (const port of cfg.comfy.attachPorts ?? []) {
    if (port === cfg.comfy.spawnPort) continue // that one is ours to spawn
    const hit = await probePort(port)
    if (hit) return hit
  }
  return null
}

let spawned = null // {child, pid, logPath, port, root}

export function spawnedInfo() {
  if (!spawned) return null
  return { pid: spawned.pid, port: spawned.port, logPath: spawned.logPath, alive: spawned.child.exitCode === null }
}

export async function stopSpawned(reason = 'finished') {
  if (!spawned) return false
  const { child, pid, logPath } = spawned
  spawned = null
  const label = `\n[dsh-pbr-material] stopping pid ${pid} (${reason}) at ${new Date().toISOString()}\n`
  try {
    writeFileSync(logPath, label, { flag: 'a' })
  } catch {}
  // SIGTERM is emulated on Windows; taskkill /T takes the whole tree, which is
  // what actually releases the ~5 GB of weights.
  await new Promise((resolve) => {
    const killer = spawn('taskkill', ['/PID', String(pid), '/T', '/F'], {
      stdio: 'ignore',
      windowsHide: true,
    })
    killer.on('exit', () => resolve())
    killer.on('error', () => {
      try {
        child.kill()
      } catch {}
      resolve()
    })
  })
  return true
}

/**
 * Spawn our own headless instance against its own base directory.
 * Port 8288: 8164-8263 are Windows-reserved here and fail with WinError 10013.
 */
export async function spawnHeadless(cfg, { onLog } = {}) {
  const { installDir, python, runRoot, spawnPort, startupTimeoutMs } = cfg.comfy
  const mainPy = join(installDir, 'main.py')
  if (!existsSync(mainPy)) throw new Error(`ComfyUI main.py not found: ${mainPy}`)
  if (!existsSync(python)) throw new Error(`ComfyUI python not found: ${python}`)

  const { notes } = ensureRunRoot(cfg)
  const logDir = join(runRoot, 'logs')
  mkdirSync(logDir, { recursive: true })
  const logPath = join(logDir, `comfy-${Date.now()}.log`)
  const fd = openSync(logPath, 'a')

  const args = [
    '-B',
    mainPy,
    '--port',
    String(spawnPort),
    '--listen',
    '127.0.0.1',
    '--base-directory',
    runRoot,
    '--extra-model-paths-config',
    join(runRoot, 'extra_model_paths.yaml'),
    '--disable-auto-launch',
    '--log-stdout',
    ...(cfg.comfy.extraArgs ?? []),
  ]
  const child = spawn(python, args, {
    cwd: installDir,
    stdio: ['ignore', fd, fd],
    windowsHide: true,
  })
  child.on('error', () => {})
  closeSync(fd)
  spawned = { child, pid: child.pid, logPath, port: spawnPort, root: runRoot, args }

  const tail = () => {
    try {
      return readFileSync(logPath, 'utf8').split('\n').slice(-25).join('\n')
    } catch {
      return ''
    }
  }

  const deadline = Date.now() + (startupTimeoutMs ?? 300000)
  while (Date.now() < deadline) {
    if (child.exitCode !== null) {
      spawned = null
      throw new Error(`ComfyUI exited with code ${child.exitCode}\n${tail()}`)
    }
    const hit = await probePort(spawnPort)
    if (hit) {
      onLog?.(`headless ComfyUI up on ${spawnPort} (pid ${child.pid})`)
      return { ...hit, spawnedPid: child.pid, logPath, notes }
    }
    await sleep(2000)
  }
  await stopSpawned('startup timeout')
  throw new Error(`ComfyUI did not answer on port ${spawnPort} within ${startupTimeoutMs} ms\n${tail()}`)
}

export async function attachOrSpawn(cfg, { onLog, forceSpawn = false } = {}) {
  if (!forceSpawn) {
    const hit = await findAttached(cfg)
    if (hit) {
      onLog?.(`attached to the running ComfyUI on port ${hit.port}`)
      return { ...hit, spawnedPid: null, logPath: null, attached: true, notes: [] }
    }
  }
  const hit = await spawnHeadless(cfg, { onLog })
  return { ...hit, attached: false }
}

