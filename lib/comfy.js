/**
 * ComfyUI lifecycle + REST client. No external dependencies.
 *
 * Policy (chosen by the user): ATTACH if the user's ComfyUI already answers,
 * otherwise SPAWN one headless instance of our own, and never both — a 16 GB
 * card cannot hold two copies of Klein 4B plus its text encoder.
 */
import { spawn } from 'node:child_process'
import {
  closeSync,
  existsSync,
  lstatSync,
  mkdirSync,
  openSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { basename, extname, join } from 'node:path'

import { PLUGIN_DIR } from './config.js'

const POLL_MS = 3000

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms))
}

async function getJson(url, timeoutMs = 8000) {
  const res = await fetch(url, { signal: AbortSignal.timeout(timeoutMs) })
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`)
  return res.json()
}

async function postJson(url, body, timeoutMs = 30000) {
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(body ?? {}),
    signal: AbortSignal.timeout(timeoutMs),
  })
  const text = await res.text()
  let parsed
  try {
    parsed = text ? JSON.parse(text) : {}
  } catch {
    parsed = { raw: text }
  }
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}: ${text.slice(0, 400)}`)
  return parsed
}

