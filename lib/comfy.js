const EXTRA_MODEL_PATHS = (modelsDir) => `# Generated by dsh-pbr-material.
# Points the plugin's headless instance at the authoritative model library.
comfy.pbr_material:
  base_path: '${modelsDir.replace(/\\/g, '\\\\')}'
  is_default: true
  checkpoints: checkpoints/
  clip: clip/
  clip_vision: clip_vision/
  configs: configs/
  controlnet: controlnet/
  diffusion_models: diffusion_models/
  embeddings: embeddings/
  loras: loras/
  style_models: style_models/
  text_encoders: text_encoders/
  unet: unet/
  upscale_models: upscale_models/
  vae: vae/
  vae_approx: vae_approx/
`

/**
 * Make sure the run root can actually boot: the five ComfyUI directories, the
 * node pack the pipeline needs, and a model-paths file.
 *
 * `custom_nodes` here is a REAL directory holding exactly one link — the pbrlab
 * pack shipped inside this plugin. It used to be a junction to the user's
 * install, which only worked when the pack happened to be installed there;
 * that is precisely what made the plugin unshareable. Now the headless instance
 * loads a version-matched pack and never writes into the user's ComfyUI.
 */
export function ensureRunRoot(cfg) {
  const root = cfg.comfy.runRoot
  const notes = []
  for (const d of ['input', 'output', 'temp', 'user', 'models', 'custom_nodes']) {
    mkdirSync(join(root, d), { recursive: true })
  }

  // comfy_extras is core, so it is linked from the install.
  {
    const link = join(root, 'comfy_extras')
    const target = join(cfg.comfy.installDir, 'comfy_extras')
    if (!existsSync(target)) {
      notes.push(`missing in the ComfyUI install: ${target}`)
    } else {
      let live = false
      try {
        live = statSync(link).isDirectory()
      } catch {
        live = false
      }
      if (!live) {
        if (lstatSync(link, { throwIfNoEntry: false })) rmSync(link, { recursive: true, force: true })
        try {
          symlinkSync(target, link, 'junction')
          notes.push(`linked comfy_extras -> ${target}`)
        } catch (error) {
          notes.push(`FAILED to link comfy_extras: ${error.message}`)
        }
      }
    }
  }

  // The node pack, from inside the plugin.
  {
    const bundled = join(PLUGIN_DIR, 'assets', 'pbrlab')
    const external = cfg.comfy.nodePackPath && cfg.comfy.nodePackPath.trim() ? cfg.comfy.nodePackPath : null
    const source = existsSync(join(bundled, 'nodes.py'))
      ? bundled
      : external && existsSync(join(external, 'nodes.py'))
        ? external
        : null
    const link = join(root, 'custom_nodes', 'pbrlab')
    if (!source) {
      notes.push('缺少 pbrlab 节点包（插件 assets/pbrlab 里应该有 nodes.py）')
    } else {
      const live = existsSync(join(link, 'nodes.py'))
      const pointsAt = (() => {
        try {
          return statSync(link).isDirectory()
        } catch {
          return false
        }
      })()
      if (!live || !pointsAt) {
        if (lstatSync(link, { throwIfNoEntry: false })) rmSync(link, { recursive: true, force: true })
        try {
          symlinkSync(source, link, 'junction')
          notes.push(`linked custom_nodes/pbrlab -> ${source}`)
        } catch (error) {
          notes.push(`FAILED to link pbrlab: ${error.message}`)
        }
      }
    }
  }

  const extra = join(root, 'extra_model_paths.yaml')
  if (!existsSync(extra)) {
    writeFileSync(extra, EXTRA_MODEL_PATHS(cfg.comfy.modelsDir), 'utf8')
    notes.push(`wrote ${extra}`)
  }
  return { root, notes }
}

