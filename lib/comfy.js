export class ComfyClient {
  constructor(instance) {
    this.port = instance.port
    this.base = `http://127.0.0.1:${instance.port}`
    this.instance = instance
  }

  /** Upload a local file into the instance's input directory. */
  async uploadImage(filePath, { category = 'pbr_ref' } = {}) {
    const buf = readFileSync(filePath)
    const ext = (extname(filePath) || '.png').toLowerCase()
    // ASCII-only name: the source path may contain any language, and the
    // filename travels through HTTP multipart and the graph JSON.
    const name = `${category}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}${ext}`
    const form = new FormData()
    form.append('image', new Blob([buf]), name)
    form.append('overwrite', 'true')
    form.append('type', 'input')
    const res = await fetch(`${this.base}/upload/image`, {
      method: 'POST',
      body: form,
      signal: AbortSignal.timeout(120000),
    })
    if (!res.ok) throw new Error(`upload failed: HTTP ${res.status} ${await res.text()}`)
    const out = await res.json()
    return { name: out.name ?? name, subfolder: out.subfolder ?? '', type: out.type ?? 'input' }
  }

  /** Queue a graph; throws with node_errors when ComfyUI rejects it. */
  async queue(graph, { clientId = 'dsh-pbr-material' } = {}) {
    const out = await postJson(`${this.base}/prompt`, { prompt: graph, client_id: clientId })
    if (out.node_errors && Object.keys(out.node_errors).length > 0) {
      // Keep the traceback: ComfyUI reports e.g. `KeyError: 17` only inside it.
      const detail = Object.entries(out.node_errors)
        .map(([nodeId, err]) => {
          const parts = (err.errors ?? []).map((e) => {
            const tb = e.extra_info?.traceback
            return [
              `  node ${nodeId}: ${e.type}: ${e.message}`,
              e.details ? `    details: ${e.details}` : '',
              tb ? `    traceback:\n${String(tb).split('\n').slice(-8).join('\n')}` : '',
            ]
              .filter(Boolean)
              .join('\n')
          })
          return parts.join('\n')
        })
        .join('\n')
      throw new Error(`ComfyUI rejected the graph:\n${detail}`)
    }
    if (!out.prompt_id) throw new Error(`no prompt_id in response: ${JSON.stringify(out).slice(0, 400)}`)
    return out.prompt_id
  }

  async history(promptId) {
    const all = await getJson(`${this.base}/history/${promptId}`, 30000)
    return all[promptId] ?? null
  }

  async wait(promptId, { timeoutMs = 1800000, pollMs = POLL_MS, onTick } = {}) {
    const t0 = Date.now()
    while (Date.now() - t0 < timeoutMs) {
      let entry = null
      try {
        entry = await this.history(promptId)
      } catch {
        // transient: the server may be mid-restart or busy decoding
      }
      if (entry) {
        const status = entry.status ?? {}
        for (const message of status.messages ?? []) {
          const kind = Array.isArray(message) ? message[0] : undefined
          if (kind === 'execution_error' || kind === 'execution_interrupted') {
            throw new Error(`ComfyUI ${kind}: ${JSON.stringify(message[1]).slice(0, 1200)}`)
          }
        }
        if (status.completed === true || status.status_str === 'success') {
          return { entry, elapsedMs: Date.now() - t0 }
        }
        if (status.status_str === 'error') {
          throw new Error(`ComfyUI reported error: ${JSON.stringify(status).slice(0, 1200)}`)
        }
      }
      onTick?.(Date.now() - t0)
      await sleep(pollMs)
    }
    throw new Error(`generation timed out after ${timeoutMs} ms (prompt ${promptId})`)
  }

  /** Run a graph and wait. */
  async run(graph, options = {}) {
    const promptId = await this.queue(graph, options)
    const { entry, elapsedMs } = await this.wait(promptId, options)
    return { promptId, entry, elapsedMs }
  }

  /** Node types this instance actually registered. */
  async hasNode(classType) {
    try {
      const info = await getJson(`${this.base}/object_info/${classType}`, 15000)
      return Object.prototype.hasOwnProperty.call(info, classType)
    } catch {
      return false
    }
  }

  async free() {
    try {
      await postJson(`${this.base}/free`, { unload_models: true, free_memory: true })
      return true
    } catch {
      return false
    }
  }
}

