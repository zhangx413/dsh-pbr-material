function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

/**
 * Files written under <runRoot>/output/<prefix>/.
 *
 * Deliberately a directory scan rather than a read of /history: PBRLabSaveImage16
 * returns `{"ui": {"text": [...]}}`, and ComfyUI's /history keeps only
 * SaveImage's `images` — text outputs are dropped. We chose the prefix, so the
 * scan is exact.
 */
export function collectOutputs(runRoot, prefix) {
  const dir = join(runRoot, 'output', ...prefix.split('/'))
  if (!existsSync(dir)) return []
  return walk(dir)
    .filter((f) => f.toLowerCase().endsWith('.png'))
    .map((f) => ({ path: f, name: basename(f), size: statSync(f).size }))
    .sort((a, b) => a.name.localeCompare(b.name))
}
